import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import test from 'node:test';
import {getDb} from '../frontend/src/lib/db';
import {startDisposablePostgres,createPaidGenerationTestSchema} from './helpers/disposable-postgres';
import {studioAssistancePolicy} from '../frontend/src/server/studio/assistance-policy';
import * as ledger from '../frontend/src/server/studio/assistance-ledger';

test('new Studio accounts start with Luna without spending Sol credits, and switching requires an explicit choice',async t=>{
  const pg=await startDisposablePostgres('studio-luna-default'),previous=process.env.DATABASE_URL;
  process.env.DATABASE_URL=pg.databaseUrl;
  t.after(async()=>{await getDb().end();if(previous===undefined)delete process.env.DATABASE_URL;else process.env.DATABASE_URL=previous;await pg.cleanup();});
  await createPaidGenerationTestSchema(pg.pool);
  for(const file of ['54_studio_assistance_ledger.sql','62_studio_assistance_resolutions.sql','63_studio_assistance_credits.sql'])await pg.pool.query(readFileSync('neon/migrations/'+file,'utf8'));
  const policy=studioAssistancePolicy({STUDIO_ASSISTANCE_ENABLED:'true'}),actor={userId:'new-client',projectId:'film',authMethod:'studio-session' as const,clientId:null};
  const initial=await ledger.readStudioAssistanceStatus(actor.userId,policy);
  assert.equal(initial.selectedModel,'gpt-6-luna');assert.equal(initial.mode,'sponsored_luna');
  assert.equal((await pg.pool.query('SELECT count(*)::int n FROM studio_assistance_accounts')).rows[0].n,0,'Opening status stays read-only');
  const requestId=randomUUID();const frozen=await ledger.openStudioAssistanceTurn(actor,requestId,policy);
  assert.equal(frozen.model,'gpt-6-luna');
  const call=await ledger.reserveStudioAssistanceCall({...actor,requestId,leaseId:randomUUID(),index:0,inputTokens:100,outputTokens:2200},policy);
  await ledger.settleStudioAssistanceCall(call.id,actor.userId,{id:'luna-default',model:'gpt-6-luna',service_tier:'default',usage:{input_tokens:100,input_tokens_details:{cached_tokens:0},output_tokens:50}});
  const after=await ledger.readStudioAssistanceStatus(actor.userId,policy);
  assert.equal(after.credits?.included.remaining,500);assert.equal(after.paid.enabled,false);
  assert.equal((await pg.pool.query("SELECT count(*)::int n FROM app_receipts WHERE type='charge'")).rows[0].n,0);
  const selected=await ledger.chooseStudioAssistance(actor.userId,{action:'select_sol',expectedRevision:after.revision},policy);
  assert.equal(selected.selectedModel,'gpt-6.1-sol');assert.equal(selected.paid.enabled,false);
  assert.equal((await ledger.openStudioAssistanceTurn(actor,requestId,policy)).model,'gpt-6-luna','A later choice cannot change an in-flight request');
  assert.equal((await ledger.openStudioAssistanceTurn(actor,randomUUID(),policy)).model,'gpt-6.1-sol');
  await pg.pool.query("INSERT INTO studio_assistance_accounts(user_id,sol_limit_nano_usd,luna_limit_nano_usd) VALUES('implicit-sol',1,1)");
  const oldSolActor={...actor,userId:'implicit-sol'},oldSolRequest=randomUUID();
  assert.equal((await ledger.openStudioAssistanceTurn(oldSolActor,oldSolRequest,policy)).model,'gpt-6.1-sol');
  await pg.pool.query(readFileSync('neon/migrations/66_studio_luna_default.sql','utf8'));
  assert.equal((await ledger.openStudioAssistanceTurn(oldSolActor,oldSolRequest,policy)).model,'gpt-6.1-sol','Migration cannot replace an old frozen Sol request');
  assert.equal((await ledger.readStudioAssistanceStatus('implicit-sol',policy)).selectedModel,'gpt-6-luna');
  assert.equal((await ledger.readStudioAssistanceStatus(actor.userId,policy)).selectedModel,'gpt-6.1-sol','An explicit Sol preference survives the default change');
  assert.equal((await ledger.openStudioAssistanceTurn(actor,requestId,policy)).model,'gpt-6-luna');
  const revision=(await ledger.readStudioAssistanceStatus('implicit-sol',policy)).revision;
  await pg.pool.query(readFileSync('neon/migrations/66_studio_luna_default.sql','utf8'));
  assert.equal((await ledger.readStudioAssistanceStatus('implicit-sol',policy)).revision,revision,'Reapplying the migration does not rewrite the account');
});
